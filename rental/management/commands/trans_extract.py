import copy
from pathlib import Path
from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from django.utils import timezone
from rental.i18n_tools import (
    Catalogue,
    ExtractionError,
    extract_messages,
    parse_po,
    write_po,
)

PLURAL_FORMS = {
    "en": "nplurals=2; plural=(n != 1);",
    "sq": "nplurals=2; plural=(n != 1);",
    "it": "nplurals=2; plural=(n != 1);",
    "de": "nplurals=2; plural=(n != 1);",
}

LANGUAGE_TEAM = {
    "en": "English",
    "sq": "Albanian",
    "it": "Italian",
    "de": "German",
}

SEARCH_ROOTS = ["templates", "rental", "carrental"]


class Command(BaseCommand):
    help = "Extract translatable strings into the .po catalogues (no gettext needed)."

    def add_arguments(self, parser):
        parser.add_argument(
            "--locale", "-l", action="append", dest="locales",
            help="Only process these locales (repeatable).",
        )

    def handle(self, *args, **options):
        base_dir = Path(settings.BASE_DIR)
        locale_dir = Path(settings.LOCALE_PATHS[0])

        languages = [code for code, _name in settings.LANGUAGES]
        if options.get("locales"):
            languages = [c for c in languages if c in options["locales"]]

        self.stdout.write("Scanning source…")
        try:
            messages = extract_messages(base_dir, SEARCH_ROOTS)
        except ExtractionError as exc:
            raise CommandError(f"Could not scan {exc}") from exc
        plural_count = sum(1 for m in messages if m.is_plural)
        self.stdout.write(
            f"  found {len(messages)} strings ({plural_count} with plural forms)\n"
        )

        stamp = timezone.now().strftime("%Y-%m-%d %H:%M%z")

        for language in languages:
            path = locale_dir / language / "LC_MESSAGES" / "django.po"
            existing = parse_po(path)
            previous = existing.index()

            catalogue = Catalogue()
            catalogue.metadata = {
                "Project-Id-Version": "Vantage Rentals 2.0",
                "Report-Msgid-Bugs-To": "",
                "POT-Creation-Date": stamp,
                "PO-Revision-Date": stamp,
                "Last-Translator": existing.metadata.get(
                    "Last-Translator", "Vantage Rentals Team"
                ),
                "Language-Team": LANGUAGE_TEAM.get(language, language),
                "Language": language,
                "MIME-Version": "1.0",
                "Content-Type": "text/plain; charset=UTF-8",
                "Content-Transfer-Encoding": "8bit",
                "Plural-Forms": PLURAL_FORMS.get(
                    language, "nplurals=2; plural=(n != 1);"
                ),
            }

            # msgids are authored in the source language, so that catalogue is
            # translated by definition. Filling it in keeps `trans_compile`
            # honest instead of permanently reporting English as 0% done.
            is_source = language == settings.LANGUAGE_CODE

            kept = 0
            for template in messages:
                message = copy.deepcopy(template)
                message.msgstr = ""
                message.msgstr_plural = {}

                old = previous.get(message.key)
                if old is not None:
                    message.msgstr = old.msgstr
                    message.msgstr_plural = dict(old.msgstr_plural)
                    message.flags = [f for f in old.flags if f != "fuzzy"]

                if is_source and not message.translated:
                    if message.is_plural:
                        message.msgstr_plural = {
                            0: message.msgid,
                            1: message.msgid_plural,
                        }
                    else:
                        message.msgstr = message.msgid

                if message.translated:
                    kept += 1

                if message.is_plural and not message.msgstr_plural:
                    message.msgstr_plural = {0: "", 1: ""}

                catalogue.messages.append(message)

            write_po(
                path,
                catalogue,
                header_comment=(
                    f"Vantage Rentals — {LANGUAGE_TEAM.get(language, language)}\n"
                    f"Generated by `manage.py trans_extract`.\n"
                    f"Edit msgstr values, then run `manage.py trans_compile`."
                ),
            )

            missing = len(messages) - kept
            self.stdout.write(
                f"  {language}: {len(messages)} strings, {kept} translated, "
                f"{missing} to do  ->  {path.relative_to(base_dir)}"
            )

        self.stdout.write(self.style.SUCCESS("\nCatalogues rebuilt."))
